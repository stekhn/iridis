// Extracts advance widths from the bundled TTFs into TypeScript modules the engine imports
// (run: npm run font-metrics). The layout engine measures text with these tables instead of
// canvas measureText, so line breaks are identical in every browser, in the PDF and in Node.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import fontkit from '@pdf-lib/fontkit'

const here = dirname(fileURLToPath(import.meta.url))
const FONTS_DIR = join(here, '..', 'src', 'assets', 'fonts')
const OUT_DIR = join(here, '..', 'engine', 'src', 'renderers', 'v1', 'fonts')

/** Code point ranges the table covers: ASCII, Latin-1, Latin Extended A and B, punctuation, euro. */
const RANGES: [number, number][] = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x100, 0x17f],
  [0x180, 0x24f],
  [0x2010, 0x2027],
  [0x2030, 0x203a],
  [0x20ac, 0x20ac],
]

function extract(file: string, exportName: string): string {
  const font = fontkit.create(new Uint8Array(readFileSync(join(FONTS_DIR, file))))
  const advances: Record<string, number> = {}
  let sum = 0
  let n = 0
  for (const [lo, hi] of RANGES) {
    for (let cp = lo; cp <= hi; cp++) {
      if (!font.hasGlyphForCodePoint(cp)) continue
      const w = font.glyphForCodePoint(cp).advanceWidth
      advances[String.fromCodePoint(cp)] = w
      if (cp >= 0x41 && cp <= 0x7a) {
        sum += w
        n++
      }
    }
  }
  const metrics = {
    family: font.familyName,
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascent,
    descender: font.descent,
    capHeight: font.capHeight,
    xHeight: font.xHeight,
    defaultAdvance: Math.round(sum / n),
    advances,
  }
  return (
    `// Generated by scripts/extract-font-metrics.ts from ${file}. Do not edit.\n` +
    `import type { FontMetrics } from './measure.ts'\n\n` +
    `export const ${exportName}: FontMetrics = ${JSON.stringify(metrics)}\n`
  )
}

writeFileSync(join(OUT_DIR, 'hankenBold.metrics.ts'), extract('HankenGrotesk-Bold.ttf', 'hankenBold'))
writeFileSync(join(OUT_DIR, 'hankenMedium.metrics.ts'), extract('HankenGrotesk-Medium.ttf', 'hankenMedium'))
console.log('wrote font metrics to', OUT_DIR)
